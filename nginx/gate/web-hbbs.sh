#!/bin/sh
# Addresses of the ID server (hbbs) and relays (hbbr) for AsanDesk Web (docs/ASANDESK-WEB.md).
#
# Writes /etc/nginx/web-hbbs.conf, which default.conf includes at the http level. Called by
# entrypoint.sh before nginx starts, so the file always exists.
#
#   HBBS_LAN_IP   empty  -> rd.asandesk.ir, the public name the desktop app uses
#                 set    -> that address on the local network (when the dashboard and the
#                           RustDesk servers share a network and the public address cannot be
#                           reached from inside it)
#   HBBR_LAN_IP   the relay's local address when it is not on the hbbs machine (default: HBBS_LAN_IP)
#   WEB_RELAY_LAN more relays: "relay2.asandesk.ir=192.168.1.11,relay3.asandesk.ir=192.168.1.12"
#
# Anything that does not look like an address or a host name is skipped with a line in the log.
set -eu

OUT="${WEB_HBBS_OUT:-/etc/nginx/web-hbbs.conf}"
PUBLIC=rd.asandesk.ir

# an IPv4/IPv6 address or a host name; IPv6 gets the brackets nginx needs before ":port"
addr() {
  v=$(printf '%s' "$1" | tr -d ' ')
  if [ -z "$v" ]; then
    :
  elif printf '%s' "$v" | grep -Eq '^[0-9]{1,3}(\.[0-9]{1,3}){3}$|^[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$'; then
    printf '%s' "$v"
  elif printf '%s' "$v" | grep -Eq '^[0-9A-Fa-f:]{2,39}$'; then
    printf '[%s]' "$v"
  else
    echo "web-hbbs: \"$v\" is not an IP address or host name: ignored" >&2
  fi
}

HBBS=$(addr "${HBBS_LAN_IP:-}")
HBBR=$(addr "${HBBR_LAN_IP:-}")
[ -n "$HBBR" ] || HBBR="$HBBS"

{
  echo "# generated by nginx/gate/web-hbbs.sh from HBBS_LAN_IP / HBBR_LAN_IP / WEB_RELAY_LAN: do not edit"
  echo "map \$host \$hbbs_ws { default \"${HBBS:-$PUBLIC}:21118\"; }"
  echo "map \$host \$hbbr_ws { default \"${HBBR:-$PUBLIC}:21119\"; }"
  echo "map \$relay_host \$relay_up {"
  echo "    default \"\$relay_host:21119\";"
  [ -z "$HBBR" ] || echo "    \"$PUBLIC\" \"$HBBR:21119\";"
  # relay names come from the peer (via hbbs) as /ws/relay/<name>; only *.asandesk.ir reach this map
  printf '%s\n' "${WEB_RELAY_LAN:-}" | tr ',' '\n' | while IFS= read -r pair; do
    pair=$(printf '%s' "$pair" | tr -d ' ')
    [ -n "$pair" ] || continue
    name=${pair%%=*}
    ip=$(addr "${pair#*=}")
    if [ "$name" != "$pair" ] && [ -n "$ip" ] && printf '%s' "$name" | grep -Eq '^([a-z0-9-]+\.)*asandesk\.ir$'; then
      echo "    \"$name\" \"$ip:21119\";"
    else
      echo "web-hbbs: ignoring WEB_RELAY_LAN entry \"$pair\" (want name.asandesk.ir=address)" >&2
    fi
  done
  echo "}"
} > "$OUT"

echo "web-hbbs: AsanDesk Web reaches hbbs at ${HBBS:-$PUBLIC} and the relay at ${HBBR:-$PUBLIC}." >&2
