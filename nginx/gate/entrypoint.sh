#!/bin/sh
# Secret entry for the panel (README: «آدرس مخفی پنل»).
#
# Writes /etc/nginx/panel-gate.conf from PANEL_KEY and starts nginx the way the image does.
# default.conf includes that file inside the panel server block only, so the app's API
# server (api.asandesk.ir) is never affected.
#
#   PANEL_KEY empty    -> the file is empty: the panel is open, as before.
#   PANEL_KEY valid    -> every panel request without the cookie "panel_key=<key>" gets a plain 404.
#                         Opening  https://<panel>/<key>  (or  /<key>/any/page)  sets the cookie
#                         and redirects to the page without the key.
#   PANEL_KEY invalid  -> the panel stays CLOSED (random key nobody knows) and says why in the log;
#                         a typo must never leave the panel open.
set -eu

OUT=/etc/nginx/panel-gate.conf
KEY="${PANEL_KEY:-}"

write_gate() {
  # \$ keeps the nginx variables; only $1 (the key) is filled in here
  cat > "$OUT" <<EOF
# generated by nginx/gate/entrypoint.sh from PANEL_KEY: do not edit
absolute_redirect off;

set \$gate 1;
if (\$cookie_panel_key = "$1") { set \$gate 0; }
if (\$uri ~ "^/$1(/|\$)") { set \$gate 0; }
# public paths the app and the CDN fetch without a browser
if (\$uri ~ "^/(releases/(latest|latest-beta)\.json\$|api/releases/[^/]+/download/|__errors/|__gate_404\$)") { set \$gate 0; }
if (\$gate) { rewrite ^ /__gate_404 last; }

location = /__gate_404 {
    internal;
    add_header Cache-Control "no-store" always;
    return 404;
}

location ~ ^/$1(/|\$) {
    set \$dest /;
    # \$request_uri is the raw URI (no decoded CR/LF); a tail starting with // would be an open redirect
    if (\$request_uri ~ "^/$1(?<tail>/[^/].*)\$") { set \$dest \$tail; }
    set \$secure "";
    if (\$forwarded_proto = https) { set \$secure "; Secure"; }
    add_header Set-Cookie "panel_key=$1; Path=/; Max-Age=31536000; HttpOnly; SameSite=Lax\$secure" always;
    add_header Cache-Control "no-store" always;
    return 302 \$dest;
}
EOF
}

if [ -z "$KEY" ]; then
  echo "panel-gate: PANEL_KEY is empty: the panel answers anyone who can reach this port." >&2
  : > "$OUT"
elif printf '%s' "$KEY" | grep -Eq '^[A-Za-z0-9_-]{12,64}$'; then
  echo "panel-gate: secret entry is on (cookie panel_key)." >&2
  write_gate "$KEY"
else
  echo "panel-gate: PANEL_KEY must be 12 to 64 characters: letters, digits, - and _ . The panel is CLOSED until it is fixed." >&2
  write_gate "$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')"
fi

# نشانی سرور شناسه و رله برای آسان دسک وب (HBBS_LAN_IP و ...)؛ default.conf همیشه این فایل را می‌خواند
sh /gate/web-hbbs.sh

exec nginx -g 'daemon off;'
