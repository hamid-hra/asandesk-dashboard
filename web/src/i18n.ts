const strings: Record<Lang, Record<Key, string>> = { fa, en };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('asw_lang');
    if (saved === 'fa' || saved === 'en') return saved;
  } catch {
    /* ignore */
  }
  return 'fa';
}

let current: Lang = initialLang();
const subscribers = new Set<() => void>();

function apply() {
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'fa' ? 'rtl' : 'ltr';
}
apply();

export function setLang(lang: Lang) {
  current = lang;
  try {
    localStorage.setItem('asw_lang', lang);
  } catch {
    /* ignore */
  }
  apply();
  for (const s of subscribers) s();
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (cb) => {
      subscribers.add(cb);
      return () => subscribers.delete(cb);
    },
    () => current,
  );
}

export function t(key: string, ...args: (string | number)[]): string {
  const table = strings[current] as Record<string, string>;
  let s = table[key] ?? (fa as Record<string, string>)[key] ?? key;
  for (const a of args) s = s.replace('{}', String(a));
  return s;
}

/** کد دستگاه با فاصله: 1 338 282 727 */
export function formatId(id: string): string {
  const digits = id.replace(/\s/g, '');
  if (!/^\d+$/.test(digits)) return id;
  return digits.replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

export function relativeDay(iso: string): string {
  const d = new Date(iso);
  const start = (x: Date) => new Date(x.getFullYear(), x.getMonth(), x.getDate()).getTime();
  const days = Math.round((start(new Date()) - start(d)) / 86_400_000);
  if (days <= 0) return t('asan_today');
  if (days === 1) return t('asan_yesterday');
  return t('asan_days_ago', days);
}
